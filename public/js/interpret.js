  var RULER_NAMES = { sun: '太阳', moon: '月亮', mercury: '水星', venus: '金星', mars: '火星', jupiter: '木星', saturn: '土星', uranus: '天王星', neptune: '海王星', pluto: '冥王星' };

  function degText(p) { return p.sign.name + ' ' + p.sign.deg + '\u00B0' + String(p.sign.min).padStart(2, '0'); }

  function planetBy(key, chart) {
    if (key === 'asc') return chart.asc;
    if (key === 'mc') return chart.mc;
    if (key === 'node') return chart.node;
    return chart.planets.find(function (p) { return p.key === key; });
  }

