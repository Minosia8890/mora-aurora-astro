      + (chart.livePlace ? '，现居' + chart.livePlace.name : '') + '。宫位制：' + (chart.houseSystem === 'placidus' ? 'Placidus（普拉西度）' : chart.houseSystem === 'whole' ? '整宫制' : '等宫制') + '。</p>';
    sections.push({ title: '一、基本信息', html: meta });

    var core = '<p><b>太阳' + chart.planets[0].sign.name + ' · 月亮' + chart.planets[1].sign.name + ' · 上升' + chart.asc.sign.name + '</b></p>' + buildOverview(chart, name);
    sections.push({ title: '二、核心三要素总览', html: core });

    var pl = '';
    chart.planets.forEach(function (p) { pl += '<p>' + planetText(p, chart) + '</p>'; });
    pl += '<p>' + planetText(chart.node, chart) + '</p>';
    sections.push({ title: '三、行星逐一解析', html: pl });

    var hh = '';
    for (var i = 1; i <= 12; i++) {
      var inHouse = chart.allPoints.filter(function (p) { return p.house === i; });
      var cuspSign = (chart.houseSystem === 'whole') ? '' : '（宫头 ' + (Math.floor(chart.houses[i] / 30)) + '号星座 ' + Math.floor(chart.houses[i] % 30) + '\u00B0）';
      hh += '<p><b>第' + i + '宫 · ' + KB.houses[i - 1].title + '</b>' + cuspSign + '<br>' + KB.houses[i - 1].desc;
      if (inHouse.length) hh += '<br>落入：' + inHouse.map(function (p) { return p.name; }).join('、');
      hh += '</p>';
    }
    sections.push({ title: '四、十二宫位详解', html: hh });

    var asp = '<p>共检测到 <b>' + chart.aspects.length + '</b> 组行星相位（按紧密程度排序）：</p>';
    chart.aspects.forEach(function (a) { asp += '<p>' + aspectText(a, chart) + '</p>'; });
